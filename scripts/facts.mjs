// The facts the page shares with the profile README (adr.sws.014): read them, check the page against
// them, and render the README's product table from them. check-site.mjs and readme-facts.mjs both use
// this module, so the page and the README are read by one reading of docs/facts.json.
//
// The check forbids a page that drifts from the facts, so it carries its own self-test below
// (CLAUDE.md, LESSONS 11.11.2026): pages that must pass and pages that must fail. check-site runs it
// on every run, before it trusts a green result.
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

export const SITE = 'https://sunrisesoftware.app';
export const START = '<!-- facts:start: generated by scripts/readme-facts.mjs from docs/facts.json in github.com/pkorrrhonen-cmd/sunrisesoftware-site; edit the facts there, not this table -->';
export const END = '<!-- facts:end -->';
const ARROW = '(?:→|&rarr;)';

export function loadFacts(root) {
  return JSON.parse(readFileSync(resolve(root, 'docs/facts.json'), 'utf8'));
}

// Every product in page order, with its group.
export function products(facts) {
  return facts.groups.flatMap((g) => g.products.map((p) => ({ ...p, group: g.name, place: g.place })));
}

// The state as both surfaces write it: "Live · paying customers · 2026 →".
export function stateLine(p) {
  return [p.state, p.detail, `${p.since} →`].filter(Boolean).join(' · ');
}

// The shape of the file, so a typo fails loudly instead of rendering an empty cell.
export function validateFacts(facts) {
  const errors = [];
  if (!Array.isArray(facts.groups) || facts.groups.length === 0) return ['docs/facts.json has no groups'];
  const seen = new Set();
  for (const g of facts.groups) {
    if (!g.name || !['plate', 'drawer'].includes(g.place)) errors.push(`facts group ${JSON.stringify(g.name)}: needs a name and a place (plate or drawer)`);
    for (const p of g.products || []) {
      const at = `facts ${p.name || '(no name)'}`;
      if (!p.name) errors.push(`${at}: no name`);
      if (seen.has(p.name)) errors.push(`${at}: named twice`);
      seen.add(p.name);
      if (!p.state) errors.push(`${at}: no state`);
      if (!Number.isInteger(p.since) || p.since < 2000 || p.since > 2100) errors.push(`${at}: since is not a year`);
      if (!p.text) errors.push(`${at}: no text for the README`);
      if (!p.checked) errors.push(`${at}: does not say what was checked`);
      const w = p.where || {};
      if (!w.text && !(w.label && w.href)) errors.push(`${at}: where needs a label and an href, or a text`);
      if (w.href && !/^https:\/\//.test(w.href)) errors.push(`${at}: where.href is not an https address`);
      if (p.licence && !p.text.includes(p.licence)) errors.push(`${at}: the README text does not name its licence ${p.licence}`);
      if (p.subpage && !/^\/[a-z0-9-]+\/$/.test(p.subpage)) errors.push(`${at}: subpage is not a /path/`);
      if (p.pending && (!Number.isInteger(p.pending.page_since) || !p.pending.waits_for)) errors.push(`${at}: pending needs page_since and waits_for`);
      if (p.pending && p.pending.page_since === p.since) errors.push(`${at}: pending page_since equals since, so it is no difference`);
    }
  }
  return errors;
}

const strip = (s) => s.replace(/<[^>]+>/g, '').replace(/&middot;/g, '·').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();

// A status as words and a year: "In use · 2026 → · home AMD box" is {year: 2026, words: [in use, home amd box]}.
export function parseStatus(text) {
  const t = strip(text);
  const m = t.match(new RegExp(`(\\d{4})\\s*${ARROW}`));
  const words = t.replace(new RegExp(`\\d{4}\\s*${ARROW}`), '').split('·').map((w) => w.trim().toLowerCase()).filter(Boolean);
  return { year: m ? Number(m[1]) : null, words };
}

// The products on the front page, in document order: the plates of section 02 under their group
// labels and the drawers of section 03.
export function readFrontPage(html) {
  const found = [];
  let group = null;
  const re = /<div class="group"[^>]*>([^<]+)<\/div>|<span class="num"[^>]*>§03 · ([^<]+)<\/span>|<article class="(plate|drawer)[^"]*"[^>]*>([\s\S]*?)<\/article>/g;
  for (const m of html.matchAll(re)) {
    if (m[1] || m[2]) { group = strip(m[1] || m[2]); continue; }
    const place = m[3];
    const block = m[4];
    if (place === 'plate') {
      const name = block.match(/<h3[^>]*>([^<]+)<\/h3>/);
      const status = block.match(/<span class="status[^"]*"[^>]*>([\s\S]*?)<\/span>/);
      found.push({ name: name ? strip(name[1]) : null, group, place, status: status ? parseStatus(status[1]) : null, block });
    } else {
      const head = block.match(/<span class="y">([^<]*)<\/span><span class="n">([^<]+)<small>([^<]*)<\/small><\/span>/);
      const year = head ? parseStatus(head[1]).year : null;
      found.push({ name: head ? strip(head[2]) : null, group, place, status: head ? { year, words: parseStatus(head[3]).words } : null, block });
    }
  }
  return found;
}

// A sub-page's own status line: the first status span on the page.
export function readSubpageStatus(html) {
  const s = html.match(/<span class="status[^"]*"[^>]*>([\s\S]*?)<\/span>/);
  return s ? parseStatus(s[1]) : null;
}

const sameWords = (a, b) => a.length === b.length && a.every((w) => b.includes(w));

// One surface's status against one fact. Returns failures; a pending difference is a note, not a failure.
function compareStatus(p, status, where, notes) {
  const fails = [];
  if (!status) return [`${where}: ${p.name} has no status line`];
  const expected = [p.state, p.detail].filter(Boolean).map((w) => w.toLowerCase());
  if (!sameWords(status.words, expected)) fails.push(`${where}: ${p.name} says "${status.words.join(' · ')}", the facts say "${expected.join(' · ')}"`);
  if (status.year === p.since) {
    if (p.pending) fails.push(`${where}: ${p.name} now says ${p.since} →, so its pending record in docs/facts.json is stale: remove it`);
  } else if (p.pending && status.year === p.pending.page_since) {
    notes.push(`pending: ${where} ${p.name} says ${status.year} →, the facts say ${p.since} → (${p.pending.waits_for})`);
  } else {
    fails.push(`${where}: ${p.name} says ${status.year ?? 'no year'} →, the facts say ${p.since} →`);
  }
  return fails;
}

// The front page and the sub-pages against the facts. pagesHtml maps a sub-page path to its HTML.
export function checkPages(facts, frontHtml, pagesHtml = {}) {
  const fails = [];
  const notes = [];
  const want = products(facts);
  const got = readFrontPage(frontHtml);
  const wantNames = want.map((p) => p.name);
  const gotNames = got.map((g) => g.name);
  for (const g of got) if (!wantNames.includes(g.name)) fails.push(`index.html: ${g.name} is on the page but has no fact in docs/facts.json`);
  for (const p of want) if (!gotNames.includes(p.name)) fails.push(`index.html: ${p.name} is in docs/facts.json but not on the page`);
  if (fails.length === 0 && wantNames.join('|') !== gotNames.join('|')) fails.push(`index.html: the products are in a different order than in docs/facts.json (page: ${gotNames.join(', ')})`);
  for (const p of want) {
    const g = got.find((x) => x.name === p.name);
    if (!g) continue;
    if (g.group !== p.group) fails.push(`index.html: ${p.name} is under "${g.group}", the facts say "${p.group}"`);
    if (g.place !== p.place) fails.push(`index.html: ${p.name} is a ${g.place}, the facts say a ${p.place}`);
    fails.push(...compareStatus(p, g.status, 'index.html', notes));
    if (p.where.href) {
      const rel = p.where.href.startsWith(SITE) ? p.where.href.slice(SITE.length) : null;
      if (!g.block.includes(`href="${p.where.href}"`) && !(rel && g.block.includes(`href="${rel}"`))) {
        fails.push(`index.html: ${p.name} does not link ${p.where.href}`);
      }
    }
    if (p.licence && !g.block.includes(p.licence)) fails.push(`index.html: ${p.name} does not name its licence ${p.licence}`);
    if (p.subpage) {
      const html = pagesHtml[p.subpage];
      if (html === undefined) fails.push(`${p.subpage}: ${p.name}'s sub-page was not found`);
      else fails.push(...compareStatus(p, readSubpageStatus(html), p.subpage, notes));
    }
  }
  return { fails, notes };
}

const cell = (s) => s.replace(/\|/g, '\\|');
function whereCell(w) {
  if (w.text) return cell(w.text);
  return cell(`${w.before || ''}[${w.label}](${w.href})${w.after || ''}`);
}

// The README's product table: one table per group, in the page's order (profile-readme.md GH.16).
export function renderReadmeBlock(facts, eol = '\n') {
  const lines = [START];
  for (const g of facts.groups) {
    lines.push('', `### ${g.name}`, '', '| Product | What it is | State | Where |', '|---|---|---|---|');
    for (const p of g.products) lines.push(`| ${cell(p.name)} | ${cell(p.text)} | ${cell(stateLine(p))} | ${whereCell(p.where)} |`);
  }
  lines.push('', END);
  return lines.join(eol);
}

// The block as it stands in a README, or null when the markers are missing.
export function readmeBlock(readme) {
  const a = readme.indexOf('<!-- facts:start');
  const b = readme.indexOf(END);
  if (a < 0 || b < a) return null;
  return { start: a, end: b + END.length, text: readme.slice(a, b + END.length) };
}

// The self-test. A small page with one plate group and one drawer, and facts for it; every case
// names what it proves. check-site fails when any case gives the wrong answer.
export function selfTest() {
  const facts = {
    groups: [
      { name: 'Commercial products', place: 'plate', products: [
        { name: 'Alpha', state: 'Live', detail: 'paying customers', since: 2026, where: { label: 'alpha.app', href: 'https://alpha.app' }, text: 't', checked: 'c' },
      ] },
      { name: 'Also in production', place: 'drawer', products: [
        { name: 'Beta', state: 'Closed beta', since: 2026, where: { label: 'beta.app', href: 'https://beta.app' }, text: 't', checked: 'c' },
      ] },
    ],
  };
  const page = (alpha, beta, extra = '') => `<div class="group" data-reveal>Commercial products</div>
<article class="plate"><div><span class="status" data-reveal><i></i>${alpha}</span><h3 data-reveal>Alpha</h3><a class="btn" href="https://alpha.app">alpha.app</a></div></article>
<span class="num" data-reveal>§03 · Also in production</span>
<article class="drawer"><button class="drawer-head"><span class="y">${beta[0]}</span><span class="n">Beta<small>${beta[1]}</small></span></button><a class="link" href="https://beta.app">beta.app</a></article>${extra}`;
  const withPending = JSON.parse(JSON.stringify(facts));
  withPending.groups[1].products[0].pending = { page_since: 2025, waits_for: 'self-test' };
  const extraDrawer = '<article class="drawer"><button class="drawer-head"><span class="y">2026 →</span><span class="n">Gamma<small>live</small></span></button></article>';
  const cases = [
    ['a page that matches its facts passes', facts, page('Live · paying customers · 2026 →', ['2026 →', 'closed beta']), 0],
    ['the year written as &rarr; passes', facts, page('Live · paying customers · 2026 &rarr;', ['2026 &rarr;', 'closed beta']), 0],
    ['a plate with the wrong year fails', facts, page('Live · paying customers · 2024 →', ['2026 →', 'closed beta']), 1],
    ['a drawer with the wrong state fails', facts, page('Live · paying customers · 2026 →', ['2026 →', 'beta']), 1],
    ['a plate with a state word the facts do not have fails', facts, page('Live · paying customers · free · 2026 →', ['2026 →', 'closed beta']), 1],
    ['a product on the page without a fact fails', facts, page('Live · paying customers · 2026 →', ['2026 →', 'closed beta'], extraDrawer), 1],
    ['a fact missing from the page fails', facts, page('Live · paying customers · 2026 →', ['2026 →', 'closed beta']).replace(/<article class="drawer">[\s\S]*<\/article>/, ''), 1],
    ['a plate that does not link its address fails', facts, page('Live · paying customers · 2026 →', ['2026 →', 'closed beta']).replace('href="https://alpha.app"', 'href="https://other.app"'), 1],
    ['a pending old year passes as a note', withPending, page('Live · paying customers · 2026 →', ['2025 →', 'closed beta']), 0],
    ['a pending record is stale once the page is fixed', withPending, page('Live · paying customers · 2026 →', ['2026 →', 'closed beta']), 1],
    ['a pending record accepts only its own old year', withPending, page('Live · paying customers · 2026 →', ['2024 →', 'closed beta']), 1],
  ];
  const broken = [];
  for (const [what, f, html, expected] of cases) {
    const { fails } = checkPages(f, html);
    if ((fails.length === 0) !== (expected === 0)) broken.push(`facts check broken: ${what} (got ${fails.length} failure(s): ${fails.join('; ') || 'none'})`);
  }
  const rendered = renderReadmeBlock(facts);
  if (!rendered.includes('| Alpha | t | Live · paying customers · 2026 → | [alpha.app](https://alpha.app) |')) broken.push('facts render broken: the Alpha row is not as written');
  if (!rendered.startsWith(START) || !rendered.endsWith(END)) broken.push('facts render broken: the markers are missing');
  if (validateFacts(facts).length) broken.push(`facts validation broken: it rejects good facts (${validateFacts(facts).join('; ')})`);
  const bad = JSON.parse(JSON.stringify(facts));
  bad.groups[0].products[0].since = 26;
  delete bad.groups[1].products[0].checked;
  if (validateFacts(bad).length !== 2) broken.push('facts validation broken: it does not catch a bad year and a missing checked');
  return broken;
}
